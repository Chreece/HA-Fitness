SCIENTIFIC_LANGUAGES = (
    "en", "el", "de", "fr", "es", "it", "pt", "nl",
    "pl", "ru", "uk", "tr", "zh", "ja", "ko",
)


def _catalog(rows: dict[str, tuple[str, ...]]) -> dict[str, dict[str, str]]:
    result = {language: {} for language in SCIENTIFIC_LANGUAGES}
    for metric, values in rows.items():
        if len(values) != len(SCIENTIFIC_LANGUAGES):
            raise RuntimeError(
                f"Scientific formula {metric!r} has {len(values)} translations; "
                f"expected {len(SCIENTIFIC_LANGUAGES)}"
            )
        for language, value in zip(SCIENTIFIC_LANGUAGES, values, strict=True):
            if not str(value).strip():
                raise RuntimeError(f"Scientific formula {language}.{metric} is empty")
            result[language][metric] = value
    return result


